"""
G-code metadata extraction for first-layer parameters and bounds.
"""

from __future__ import annotations

import hashlib
import logging
import re
from pathlib import Path
from typing import NamedTuple

from sensing_voxel.core.models import FirstLayerBounds, FirstLayerParams, GeometryAnalysis

logger = logging.getLogger(__name__)

# PrusaSlicer / OrcaSlicer / Cura comment patterns
COMMENT_PATTERNS = {
    "layer_height": re.compile(r";\s*layer_height\s*=\s*([\d.]+)", re.IGNORECASE),
    "first_layer_height": re.compile(r";\s*first_layer_height\s*=\s*([\d.]+)", re.IGNORECASE),
    "first_layer_temperature": re.compile(
        r";\s*(?:first_layer_temperature|temperature|nozzle_temperature)\s*=\s*([\d.]+)",
        re.IGNORECASE,
    ),
    "first_layer_bed_temperature": re.compile(
        r";\s*(?:first_layer_bed_temperature|bed_temperature|hot_plate_temp)\s*=\s*([\d.]+)",
        re.IGNORECASE,
    ),
    "first_layer_speed": re.compile(
        r";\s*(?:first_layer_speed|initial_layer_speed|initial_layer_print_speed)\s*=\s*([\d.]+)",
        re.IGNORECASE,
    ),
    "filament_used_mm": re.compile(r";\s*filament used\s*\[mm\]\s*=\s*([\d.]+)", re.IGNORECASE),
    "filament_used_g": re.compile(
        r";\s*(?:filament used\s*\[g\]|total filament weight|total_wipe_tower_cost)\s*=?\s*([\d.]+)",
        re.IGNORECASE,
    ),
    "estimated_time": re.compile(
        r";\s*(?:estimated[_ ]?(?:printing[_ ]?)?time|TIME|total_estimated_time)\s*[:=]\s*(\d+)",
        re.IGNORECASE,
    ),
    "total_layers": re.compile(
        r";\s*total layer(?:s| number|_count|s)\s*[:=]\s*(\d+)", re.IGNORECASE
    ),
    "slicer": re.compile(r";\s*(?:generated by|sliced by)\s+([\w\s]+)", re.IGNORECASE),
    "printer_model": re.compile(r";\s*printer_model\s*=\s*(\w+)", re.IGNORECASE),
    "filament_type": re.compile(
        r";\s*filament_type\s*[:=]\s*([^;\r\n]+)", re.IGNORECASE
    ),
}

# G1 move pattern for first-layer bounds parsing
G1_MOVE_PATTERN = re.compile(
    r"G1\s+(?:.*?X([\d.]+))?(?:.*?Y([\d.]+))?(?:.*?E[\d.]+)", re.IGNORECASE
)
# Layer change markers
LAYER_CHANGE_PATTERN = re.compile(r";\s*(?:LAYER_CHANGE|AFTER_LAYER_CHANGE|;Z:)", re.IGNORECASE)

# Overhang detection: fan speed changes often indicate overhangs
OVERHANG_FAN_PATTERN = re.compile(
    r";\s*(?:overhang|support)\s*(?:fan|cooling)\s*(?:speed)?\s*=?\s*([\d.]+)%?",
    re.IGNORECASE,
)
# Bridge detection: bridge settings often marked in comments
BRIDGE_PATTERN = re.compile(
    r";\s*bridge\s*(?:speed|settings)?\s*[:=]?\s*([\d.]+)?",
    re.IGNORECASE,
)
# Thin wall detection: very short extrusion moves
THIN_WALL_PATTERN = re.compile(
    r";\s*(?:thin|wall)_?thickness\s*[:=]?\s*([\d.]+)?",
    re.IGNORECASE,
)
# Max overhang angle pattern (from PrusaSlicer/OrcaSlicer)
OVERHANG_ANGLE_PATTERN = re.compile(
    r";\s*(?:max_?)?overhang\s*(?:angle)?\s*[:=]?\s*([\d.]+)\s*°?",
    re.IGNORECASE,
)
# Support interface pattern (detects if tree/support/normal)
SUPPORT_INTERFACE_PATTERN = re.compile(
    r";\s*support(?:_type|s)\s*[:=]?\s*(\w+)",
    re.IGNORECASE,
)

# Overhang angle threshold (degrees from vertical)
OVERHANG_ANGLE_THRESHOLD = 60.0
# Thin wall threshold in mm
THIN_WALL_THRESHOLD_MM = 0.5


class OverhangInfo(NamedTuple):
    """Information about detected overhangs in a layer"""

    layer: int
    approx_angle: float
    line_count: int


class GeometryAnalyzer:
    """Analyze G-code for geometry features that may require special handling."""

    @staticmethod
    def analyze_geometry(gcode_path: Path) -> GeometryAnalysis:
        """
        Analyze G-code file for geometric features:
        - Overhangs (>60° from vertical)
        - Bridges
        - Thin walls

        Args:
            gcode_path: Path to G-code file

        Returns:
            GeometryAnalysis with detected features and warnings
        """
        warnings = []
        has_overhangs = False
        has_bridges = False
        has_thin_walls = False
        max_overhang_angle = None
        wall_thickness_min = None
        current_layer = 0
        overhang_layers: list[OverhangInfo] = []

        try:
            with open(gcode_path, errors="replace") as f:
                for line in f:
                    # Layer tracking
                    layer_match = LAYER_CHANGE_PATTERN.search(line)
                    if layer_match:
                        current_layer = (
                            int(layer_match.group(1))
                            if layer_match.group(1).isdigit()
                            else current_layer + 1
                        )

                    # Overhang detection
                    overhang_match = OVERHANG_FAN_PATTERN.search(line)
                    if overhang_match:
                        has_overhangs = True
                        angle = float(overhang_match.group(1))
                        if max_overhang_angle is None or angle > max_overhang_angle:
                            max_overhang_angle = angle
                        if angle >= OVERHANG_ANGLE_THRESHOLD:
                            overhang_layers.append(
                                OverhangInfo(layer=current_layer, approx_angle=angle, line_count=1)
                            )

                    # Explicit overhang angle comments (PrusaSlicer/OrcaSlicer)
                    angle_match = OVERHANG_ANGLE_PATTERN.search(line)
                    if angle_match:
                        angle = float(angle_match.group(1))
                        has_overhangs = True
                        if max_overhang_angle is None or angle > max_overhang_angle:
                            max_overhang_angle = angle
                        if angle >= OVERHANG_ANGLE_THRESHOLD:
                            overhang_layers.append(
                                OverhangInfo(layer=current_layer, approx_angle=angle, line_count=1)
                            )

                    # Bridge detection
                    bridge_match = BRIDGE_PATTERN.search(line)
                    if bridge_match:
                        has_bridges = True

                    # Thin wall detection
                    thin_match = THIN_WALL_PATTERN.search(line)
                    if thin_match:
                        thickness = float(thin_match.group(1))
                        if wall_thickness_min is None or thickness < wall_thickness_min:
                            wall_thickness_min = thickness
                        if thickness <= THIN_WALL_THRESHOLD_MM:
                            has_thin_walls = True

        except OSError as e:
            logger.error(f"Failed to analyze G-code geometry: {e}")
            return GeometryAnalysis(
                has_overhangs=False,
                has_bridges=False,
                has_thin_walls=False,
                warnings=[f"Failed to read file: {e}"],
            )

        # Generate warnings based on analysis
        if has_overhangs and max_overhang_angle and max_overhang_angle >= OVERHANG_ANGLE_THRESHOLD:
            warnings.append(
                f"Steep overhangs detected (max {max_overhang_angle:.1f}°) - tree supports recommended"
            )
            if overhang_layers:
                layers_str = ", ".join(str(ol.layer) for ol in overhang_layers[:5])
                warnings.append(f"Overhang layers: {layers_str}")

        if has_bridges:
            warnings.append("Bridge sections detected - ensure adequate cooling")

        if has_thin_walls:
            warnings.append(
                f"Thin walls detected (min {wall_thickness_min:.2f}mm) - may require slower speeds"
            )

        return GeometryAnalysis(
            has_overhangs=has_overhangs,
            has_bridges=has_bridges,
            has_thin_walls=has_thin_walls,
            max_overhang_angle=max_overhang_angle,
            wall_thickness_min_mm=wall_thickness_min,
            warnings=warnings,
        )

    @staticmethod
    def should_recommend_tree_supports(analysis: GeometryAnalysis) -> bool:
        """
        Determine if tree supports should be recommended based on geometry analysis.

        Tree supports are recommended when:
        - Overhangs >60° are detected
        - The model has complex organic shapes

        Args:
            analysis: GeometryAnalysis from analyze_geometry()

        Returns:
            True if tree supports should be recommended
        """
        if not analysis.has_overhangs:
            return False

        if analysis.max_overhang_angle is None:
            return False

        return analysis.max_overhang_angle >= OVERHANG_ANGLE_THRESHOLD

    @staticmethod
    def generate_support_recommendation(analysis: GeometryAnalysis) -> str | None:
        """
        Generate a human-readable recommendation message for support settings.

        Args:
            analysis: GeometryAnalysis from analyze_geometry()

        Returns:
            Recommendation message or None if no special support needed
        """
        if not GeometryAnalyzer.should_recommend_tree_supports(analysis):
            return None

        angle = analysis.max_overhang_angle or 0.0
        return (
            f"⚠️ Steep overhangs detected ({angle:.1f}° from vertical).\n"
            f"Recommendation: Enable tree supports for better surface quality and easier removal.\n"
            f"Reply with 'tree' to enable tree supports, or 'normal' for standard supports."
        )


class GcodeMetadataExtractor:
    """Extract print metadata from exact G-code bytes or files."""

    @staticmethod
    def extract_metadata_bytes(content: bytes) -> dict:
        """Extract metadata from the exact immutable G-code byte snapshot."""
        header = content[:10240].decode("utf-8", errors="replace")
        metadata = {}
        string_keys = {"slicer", "printer_model", "filament_type"}
        for key, pattern in COMMENT_PATTERNS.items():
            match = pattern.search(header)
            if match:
                value = match.group(1).strip()
                if key in string_keys:
                    metadata[key] = value
                elif key in ("total_layers", "estimated_time"):
                    metadata[key] = int(value)
                else:
                    try:
                        metadata[key] = float(value)
                    except ValueError:
                        metadata[key] = value
        return metadata

    @staticmethod
    def extract_metadata(gcode_path: Path) -> dict:
        """Extract metadata from G-code comment headers."""
        try:
            return GcodeMetadataExtractor.extract_metadata_bytes(gcode_path.read_bytes())
        except OSError as e:
            logger.error(f"Failed to read G-code file: {e}")
            return {}

    @staticmethod
    def extract_first_layer_params(gcode_path: Path) -> FirstLayerParams | None:
        """Extract first-layer parameters from G-code comments."""
        try:
            with open(gcode_path, errors="replace") as f:
                header = f.read(10240)
        except OSError:
            return None

        def find_float(pattern_key: str) -> float | None:
            m = COMMENT_PATTERNS.get(pattern_key, re.compile("$^")).search(header)
            return float(m.group(1)) if m else None

        layer_height = find_float("first_layer_height") or find_float("layer_height")
        nozzle_temp = find_float("first_layer_temperature")
        bed_temp = find_float("first_layer_bed_temperature")
        speed = find_float("first_layer_speed")

        if layer_height is None or nozzle_temp is None or bed_temp is None or speed is None:
            logger.debug("Incomplete first-layer params in G-code")
            return None

        return FirstLayerParams(
            layer_height=layer_height,
            nozzle_temp=nozzle_temp,
            bed_temp=bed_temp,
            speed=speed,
        )

    @staticmethod
    def extract_first_layer_bounds(gcode_path: Path) -> FirstLayerBounds | None:
        """Extract XY bounding box of first-layer moves from G-code."""
        min_x = float("inf")
        max_x = float("-inf")
        min_y = float("inf")
        max_y = float("-inf")
        found_moves = False

        try:
            with open(gcode_path, errors="replace") as f:
                for line in f:
                    # Stop after first layer change
                    if LAYER_CHANGE_PATTERN.search(line) and found_moves:
                        break

                    m = G1_MOVE_PATTERN.match(line)
                    if m:
                        x_str, y_str = m.group(1), m.group(2)
                        if x_str:
                            x = float(x_str)
                            min_x = min(min_x, x)
                            max_x = max(max_x, x)
                            found_moves = True
                        if y_str:
                            y = float(y_str)
                            min_y = min(min_y, y)
                            max_y = max(max_y, y)
                            found_moves = True
        except OSError:
            return None

        if not found_moves or min_x == float("inf"):
            return None

        return FirstLayerBounds(min_x=min_x, max_x=max_x, min_y=min_y, max_y=max_y)

    @staticmethod
    def compute_file_hash(file_path: Path) -> str:
        """Compute SHA-256 hash of a file."""
        sha256 = hashlib.sha256()
        with open(file_path, "rb") as f:
            for chunk in iter(lambda: f.read(8192), b""):
                sha256.update(chunk)
        return sha256.hexdigest()
